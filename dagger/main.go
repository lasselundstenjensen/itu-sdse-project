package main

import (
	"context"
	"fmt"
	"strings"
	"time"

	"dagger/pipeline/internal/dagger"
	//"dagger.io/dagger/dag"
)

type Pipeline struct{}

// Env builds the Python environment with the project's dependencies installed
func (m *Pipeline) Env(
	// +defaultPath="/"
	// +ignore=[".git", ".venv", "**/__pycache__", "dagger"]
	source *dagger.Directory,
) *dagger.Container {
	return dag.Container().
		From("python:3.10-slim").
		WithMountedCache("/root/.cache/pip", dag.CacheVolume("pip-cache")). // reuse downloaded wheels
		// CPU-only torch wheels: much smaller than the default CUDA build
		WithEnvVariable("PIP_EXTRA_INDEX_URL", "https://download.pytorch.org/whl/cpu").
		WithWorkdir("/app").
		// Copy ONLY requirements.txt first, so this install step stays cached
		// until requirements.txt itself changes (code edits won't trigger a reinstall).
		WithFile("/app/requirements.txt", source.File("requirements.txt")).
		WithExec([]string{"sh", "-c", "grep -v '^-e' requirements.txt > /tmp/req.txt && pip install -r /tmp/req.txt"}).
		// Now bring in the rest of the code; only this cheap step reruns on code changes
		WithDirectory("/app", source).
		WithExec([]string{"pip", "install", "--no-deps", "-e", "."})
}

// Train runs the training script and returns the artifacts directory
// (vial_cnn_model.pth, model_results.json, drift/class/image stats JSONs)
func (m *Pipeline) Train(
	// +defaultPath="/"
	// +ignore=[".git", ".venv", "**/__pycache__", "dagger", "artifacts", "mlflow-state", "models"]
	source *dagger.Directory,
) *dagger.Directory {
	return m.trained(source).Directory("/app/artifacts")
}

// Deploy trains the model, then runs deployment.py: picks the best MLflow run,
// promotes it to Production, exports it, serves it locally and smoke-tests
// the endpoint + drift check. Returns the exported servable model (models/model).
func (m *Pipeline) Deploy(
	// +defaultPath="/"
	// +ignore=[".git", ".venv", "**/__pycache__", "dagger", "artifacts", "mlflow-state", "models"]
	source *dagger.Directory,
) *dagger.Directory {
	return m.trained(source).
		WithExec([]string{"python", "./source/deployment.py"}).
		Directory("/app/models/model")
}

// trained is the environment after training.py has run, so artifacts/,
// mlflow-state/ and data/ exist for later steps. Not exposed to the CLI.
// Train and Deploy share this step, so with the same source the training
// run is cached and not repeated.
func (m *Pipeline) trained(source *dagger.Directory) *dagger.Container {
	return m.Env(source).
		WithExec([]string{"python", "./source/training.py"})
}

// ServeImage builds the slim serving image: a fresh python:3.10-slim with
// ONLY what is needed to answer prediction requests. It does not build on
// Env, which has the whole dev requirements.txt (jupyter, ruff, ...) and the
// whole repo.
//
// Contents of the image (workdir /app):
//
//	models/model/                         exported model (output of Deploy)
//	artifacts/drift_baseline_stats.json   drift baseline (output of training)
//	source/serve.py, source/deployment.py the web server + drift functions
//
// Try it locally:
//
//	dagger call serve-image as-service --args=uvicorn,source.serve:app,--host,0.0.0.0,--port,5001 up --ports 5001:5001
func (m *Pipeline) ServeImage(
	// +defaultPath="/"
	// +ignore=[".git", ".venv", "**/__pycache__", "dagger", "artifacts", "mlflow-state", "models"]
	source *dagger.Directory,
) *dagger.Container {
	model := m.Deploy(source)
	baseline := m.trained(source).File("/app/artifacts/drift_baseline_stats.json")

	return dag.Container().
		From("python:3.10-slim"). // must match the model's python_env.yaml (3.10)
		WithMountedCache("/root/.cache/pip", dag.CacheVolume("pip-cache")).
		// CPU-only torch: the CUDA build is several GB and the server has no GPU
		WithEnvVariable("PIP_EXTRA_INDEX_URL", "https://download.pytorch.org/whl/cpu").
		WithWorkdir("/app").
		// 1) Install dependencies first, so this big layer is reused as long
		//    as the two requirement files don't change.
		//    models/model/requirements.txt is generated by MLflow and pins the
		//    exact versions the model was trained with. Its "mlflow==X" is
		//    swapped for "mlflow-skinny==X": same library and version, but
		//    without the tracking-server/UI extras (pyarrow, scikit-learn,
		//    matplotlib, flask, sqlalchemy, ...) - ~400 MB smaller image.
		WithFile("/app/models/model/requirements.txt", model.File("requirements.txt")).
		WithFile("/app/requirements-serve.txt", source.File("requirements-serve.txt")).
		WithExec([]string{"sh", "-c",
			"sed 's/^mlflow==/mlflow-skinny==/' models/model/requirements.txt > /tmp/model-req.txt" +
				" && pip install -r /tmp/model-req.txt -r requirements-serve.txt"}).
		WithoutEnvVariable("PIP_EXTRA_INDEX_URL").
		// 2) Then the small, frequently changing parts: model + code.
		WithDirectory("/app/models/model", model).
		WithFile("/app/artifacts/drift_baseline_stats.json", baseline).
		WithFile("/app/source/serve.py", source.File("source/serve.py")).
		WithFile("/app/source/deployment.py", source.File("source/deployment.py")).
		// 3) How the container starts. Port must match http_port in app.yaml.
		WithExposedPort(5001).
		WithEntrypoint([]string{"uvicorn", "source.serve:app", "--host", "0.0.0.0", "--port", "5001"})
}

// Publish builds the serving image (ServeImage) and pushes it to
// ghcr.io/<owner>/model-serve:<tag>. Returns the image ref.
func (m *Pipeline) Publish(
	ctx context.Context,
	// +defaultPath="/"
	// +ignore=[".git", ".venv", "**/__pycache__", "dagger", "artifacts", "mlflow-state", "models"]
	source *dagger.Directory,
	owner string,
	tag string,
	ghUser string,
	ghToken *dagger.Secret,
) (string, error) {
	ref := fmt.Sprintf("ghcr.io/%s/model-serve:%s", strings.ToLower(owner), tag)
	return m.ServeImage(source).
		WithRegistryAuth("ghcr.io", ghUser, ghToken).
		Publish(ctx, ref)
}

// DeployApp fills __OWNER__/__TAG__ in the app spec and creates or updates
// the app on DigitalOcean. Use the same owner and tag as Publish.
func (m *Pipeline) DeployApp(
	ctx context.Context,
	// +defaultPath="/infra/digitalocean/app.yaml"
	spec *dagger.File,
	owner string,
	tag string,
	doToken *dagger.Secret,
) (string, error) {
	content, err := spec.Contents(ctx)
	if err != nil {
		return "", err
	}
	filled := strings.NewReplacer("__OWNER__", strings.ToLower(owner), "__TAG__", tag).Replace(content)

	script := `APP_ID=$(doctl apps list --format ID,Spec.Name --no-header | awk '$2=="mlops-itu-jtk"{print $1}')
if [ -z "$APP_ID" ]; then doctl apps create --spec /app.yaml --wait
else doctl apps update "$APP_ID" --spec /app.yaml --wait; fi`

	return dag.Container().
		From("digitalocean/doctl:latest").
		WithSecretVariable("DIGITALOCEAN_ACCESS_TOKEN", doToken).
		WithNewFile("/app.yaml", filled).
		// Dagger caches results; this forces the deploy to run every time
		WithEnvVariable("CACHE_BUSTER", time.Now().String()).
		WithExec([]string{"sh", "-c", script}).
		Stdout(ctx)
}
